param([string]$OutputDirectory = (Join-Path (Split-Path $PSScriptRoot) 'licenses'))
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
New-Item -ItemType Directory -Force -Path $OutputDirectory | Out-Null

# Filter the resolved graph, not just Cargo.toml: include transitive dependencies
# and proc macros, but exclude dependencies used only on other operating systems.
$packages = @{}
foreach ($target in @('x86_64-pc-windows-msvc', 'i686-pc-windows-msvc')) {
    $json = & cargo metadata --locked --offline --format-version 1 --filter-platform $target --manifest-path (Join-Path $root 'Cargo.toml')
    if ($LASTEXITCODE) { throw "Cannot read locked dependency metadata for $target" }
    $metadata = ($json -join "`n") | ConvertFrom-Json
    $nodes = @{}
    foreach ($node in $metadata.resolve.nodes) { $nodes[$node.id] = $node }
    $seen = @{}
    $queue = [Collections.Generic.Queue[string]]::new()
    $queue.Enqueue($metadata.resolve.root)
    while ($queue.Count) {
        $id = $queue.Dequeue()
        if ($seen.ContainsKey($id)) { continue }
        $seen[$id] = $true
        foreach ($dependency in $nodes[$id].dependencies) { $queue.Enqueue($dependency) }
    }
    foreach ($package in $metadata.packages) {
        if ($package.source -and $seen.ContainsKey($package.id)) { $packages[$package.id] = $package }
    }
}
$text = [Text.StringBuilder]::new()
[void]$text.AppendLine('Rust dependency licenses for Windows x64/x86')
[void]$text.AppendLine('Generated by tools/write-license-notices.ps1 from the resolved Cargo.lock.')
[void]$text.AppendLine('Includes build/proc-macro dependencies. Upstream license alternatives are reproduced verbatim.')
foreach ($package in ($packages.Values | Sort-Object name, version)) {
    $directory = Split-Path $package.manifest_path
    $files = @(Get-ChildItem -LiteralPath $directory -File -Recurse |
        Where-Object { $_.Name -match '^(LICENSE|LICENCE|COPYING|NOTICE|COPYRIGHT)([._-]|$)' } |
        Sort-Object FullName)
    if (!$package.license -or !$files.Count) { throw "Missing license information: $($package.name) $($package.version)" }
    [void]$text.AppendLine("`n========================================================================")
    [void]$text.AppendLine("$($package.name) $($package.version) -- $($package.license)")
    [void]$text.AppendLine("Source: https://crates.io/crates/$($package.name)/$($package.version)")
    foreach ($file in $files) {
        $relative = $file.FullName.Substring($directory.Length + 1).Replace('\', '/')
        [void]$text.AppendLine("`n--- $relative ---")
        [void]$text.AppendLine([IO.File]::ReadAllText($file.FullName).TrimEnd())
    }
}
$utf8 = [Text.UTF8Encoding]::new($false)
[IO.File]::WriteAllText((Join-Path $OutputDirectory 'Rust.txt'), $text.ToString().Replace("`r`n", "`n"), $utf8)

$manifest = Get-Content -LiteralPath (Join-Path $root 'native/dependencies.json') -Raw | ConvertFrom-Json
foreach ($entry in @(@('srt', 'SRT'), @('mbedtls', 'MbedTLS'))) {
    $dependency = $manifest.($entry[0])
    $source = Join-Path $root "native/.deps/$($dependency.directory)"
    Copy-Item -LiteralPath (Join-Path $source 'LICENSE') -Destination (Join-Path $OutputDirectory "$($entry[1]).txt") -Force
    # SRT retains BSD notices inside UDT-derived source files, separately from
    # its top-level MPL license. Preserve these embedded notices in binaries too.
    $notices = [Text.StringBuilder]::new()
    [void]$notices.AppendLine("Additional embedded notices: $($entry[1]) $($dependency.version)")
    [void]$notices.AppendLine("Source archive: $($dependency.url)")
    $unique = @{}
    foreach ($subdirectory in @('srtcore', 'common', 'haicrypt', 'library', 'include')) {
        $path = Join-Path $source $subdirectory
        if (!(Test-Path -LiteralPath $path)) { continue }
        foreach ($file in (Get-ChildItem -LiteralPath $path -File -Recurse | Where-Object { $_.Extension -in @('.c', '.cpp', '.h', '.hpp') } | Sort-Object FullName)) {
            foreach ($match in [regex]::Matches([IO.File]::ReadAllText($file.FullName), '(?s)/\*.*?\*/')) {
                $notice = $match.Value.Replace("`r`n", "`n")
                if ($notice -notmatch '(?i)copyright|redistribution and use|permission is hereby granted') { continue }
                if ($unique.ContainsKey($notice)) { continue }
                $unique[$notice] = $true
                [void]$notices.AppendLine("`n--- $($file.FullName.Substring($source.Length + 1).Replace('\', '/')) ---")
                [void]$notices.AppendLine($notice)
            }
        }
    }
    [IO.File]::WriteAllText((Join-Path $OutputDirectory "$($entry[1])-THIRD-PARTY.txt"), $notices.ToString().Replace("`r`n", "`n"), $utf8)
}
Write-Output "License notices written to $OutputDirectory ($($packages.Count) Rust packages)."
